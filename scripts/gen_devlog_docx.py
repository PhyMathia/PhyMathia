def set_cn(run):
    run.font.name = "Microsoft YaHei"
    try:
        run._element.rPr.rFonts.set(__import__("docx").oxml.ns.qn("w:eastAsia"), "Microsoft YaHei")
    except Exception:
        pass

def h(text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        set_cn(r)
    return p

def para(text, bold=False, size=None, align=None, color=None, italic=False):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    r = p.add_run(text)
    set_cn(r)
    r.bold = bold
    r.italic = italic
    if size:
        r.font.size = Pt(size)
    if color:
        r.font.color.rgb = RGBColor(*color)
    return p

def bullet(text, lead=None):
    p = doc.add_paragraph(style="List Bullet")
    if lead:
        r = p.add_run(lead)
        set_cn(r); r.bold = True
        r2 = p.add_run(text)
        set_cn(r2)
    else:
        r = p.add_run(text)
        set_cn(r)
    return p

def kv_table(rows, widths=None):
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    for k, v in rows:
        c = t.add_row().cells
        c[0].text = ""
        c[1].text = ""
        rk = c[0].paragraphs[0].add_run(k); set_cn(rk); rk.bold = True
        rv = c[1].paragraphs[0].add_run(v); set_cn(rv)
    return t

def grid_table(header, data, col_widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    hdr = t.rows[0].cells
    for i, htext in enumerate(header):
        hdr[i].text = ""
        r = hdr[i].paragraphs[0].add_run(htext); set_cn(r); r.bold = True
    for row in data:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(val)); set_cn(r)
    return t

